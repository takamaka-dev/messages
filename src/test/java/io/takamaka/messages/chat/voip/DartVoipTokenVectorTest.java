import java.util.Arrays;
import org.bouncycastle.crypto.AsymmetricCipherKeyPair;
import org.bouncycastle.crypto.generators.Ed25519KeyPairGenerator;
import org.bouncycastle.crypto.params.Ed25519KeyGenerationParameters;
import org.bouncycastle.crypto.params.Ed25519PublicKeyParameters;
import org.bouncycastle.util.encoders.UrlBase64;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * DR-074 §11 «both directions»: {@code dart_voip_token_vectors.json} is GENERATED BY DART
 * (rsclient-flutter {@code test/voip_token_parity_test.dart}; this resource is a copy of its
 * {@code test/fixtures/dart_voip_token_vectors.json}) and verified here by the Java reference: every envelope
 * verifies through the type's own verifier case, passes the content check on its route, and Java — re-deriving the
 * Dart signer's key from the mnemonic — reproduces the canonical form, the signature and the {@code token_hash}
 * byte for byte.
 */
class DartVoipTokenVectorTest {

    static final ObjectMapper M = new ObjectMapper();
    static JsonNode root;

    @BeforeAll
    static void load() throws Exception {
        try (InputStream in = DartVoipTokenVectorTest.class.getResourceAsStream("/voip/dart_voip_token_vectors.json")) {
            assertNotNull(in, "missing /voip/dart_voip_token_vectors.json: copy it from rsclient-flutter test/fixtures/");
            root = M.readTree(new String(in.readAllBytes(), StandardCharsets.UTF_8));
        }
    }

    @Test
    void javaAcceptsEveryDartEnvelope_andReproducesIt() throws Exception {
        JsonNode identity = root.get("signer_identity");
        SeedGenerator.init();
        String seed = SeedGenerator.generateSeedPWH(Arrays.asList(identity.get("mnemonic").asText().split(" ")));
        SeededRandom rnd = new SeededRandom(seed, KeyContexts.WALLET_KEY_CHAIN, identity.get("key_index").asInt() + 1);
        Ed25519KeyPairGenerator gen = new Ed25519KeyPairGenerator();
        gen.init(new Ed25519KeyGenerationParameters(rnd));
        AsymmetricCipherKeyPair kp = gen.generateKeyPair();
        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        UrlBase64.encode(((Ed25519PublicKeyParameters) kp.getPublic()).getEncoded(), baos);
        final String signer = baos.toString(StandardCharsets.US_ASCII);
        assertEquals(identity.get("signer_public_key").asText(), signer, "Java derives the Dart signer's key");

        final String aud = root.get("server_audience").asText();
        int n = 0;
        for (JsonNode v : root.get("vectors")) {
            final String name = v.get("name").asText();
            final JsonNode envelope = v.get("envelope_json");
            final String op = "registervoiptoken".equals(v.get("route").asText()) ? "register" : "unregister";
            assertEquals(signer, envelope.get("from").asText(), name);
            // the server's order: the signature through the type's own case, then the content check
            assertEquals("OK", VoipTokenVectorGenerator.verdict(envelope, op, aud), name);
            assertEquals(VoipTokenRules.AUD_MISMATCH, VoipTokenVectorGenerator.verdict(envelope, op, "rschat:other"), name);

            // Java's canonical form of the parsed content IS what Dart signed
            VoipTokenRequestBean req = VoipTokenVectorGenerator.LENIENT.treeToValue(envelope, VoipTokenRequestBean.class);
            String canonical = SimpleRequestHelper.getCanonicalJson(req.getVoipTokenSignedContentBean());
            assertEquals(v.get("signed_canonical_jcs").asText(), canonical, name);
            assertTrue(ChatSignatureVerifier.verifyEd25519(signer, v.get("signature_b64url").asText(), canonical).isValid(), name);
            // and Java signing the same bytes with the same key gives the Dart signature
            assertEquals(v.get("signature_b64url").asText(), TkmCypherProviderBCED25519.sign(kp, canonical).getSignature(), name);
            assertEquals(v.get("token_hash").asText(), VoipTokenRules.tokenHash(req.getVoipTokenSignedContentBean().getEnv(),
                    req.getVoipTokenSignedContentBean().getTp(), req.getVoipTokenSignedContentBean().getVt()), name);
            n++;
        }
        assertEquals(3, n);
    }
}
